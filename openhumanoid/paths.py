"""Repo path helpers. The repo root is the nearest ancestor containing AGENTS.md."""
from __future__ import annotations

import os
from pathlib import Path


def repo_root() -> Path:
    env = os.environ.get("OPENHUMANOID_ROOT")
    if env:
        return Path(env).resolve()
    for start in (Path.cwd(), Path(__file__).resolve().parent):
        for p in (start, *start.parents):
            if (p / "AGENTS.md").exists() and (p / "schemas").is_dir():
                return p
    raise RuntimeError("Open Humanoid repo root not found (looked for AGENTS.md + schemas/). Set OPENHUMANOID_ROOT.")


def variants_dir() -> Path:
    return repo_root() / "variants"


def catalog_dir() -> Path:
    return repo_root() / "catalog"


def schemas_dir() -> Path:
    return repo_root() / "schemas"


def coordination_dir() -> Path:
    return repo_root() / "coordination"


def generated_header(tool: str, comment: str = "#") -> str:
    return f"{comment} GENERATED by `oh {tool}`. Do not edit by hand. Change the spec or generator and re-run.\n"
