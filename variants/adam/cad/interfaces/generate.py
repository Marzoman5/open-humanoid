"""Generate Adam's region-B (upper body) interfaces: variants/adam/cad/interfaces/interfaces_upper.yaml.

    .venv/Scripts/python variants/adam/cad/interfaces/generate.py

Uses the CAD foundation generator (openhumanoid.cad.interfaces.generate) on layout_v2a_upper.yaml, then appends the A<->B contract
(contract_ab.yaml, hand-written: what region A's pelvis must provide). The generator's own `write()` targets generated/ (the
full-body file, written once region A lands); this region keeps its file next to the layout so both regions can be merged later.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT))

from openhumanoid.cad import interfaces  # noqa: E402
from openhumanoid.spec import load_spec  # noqa: E402


def main() -> int:
    spec = load_spec("adam")
    layout = interfaces.load_layout(spec, HERE / "layout_v2a_upper.yaml")
    d = interfaces.generate(spec, layout)
    # joints driven through a linkage (`drive:`): the joint axis is at `point`, the servo at `drive.servo_point`. The generator places a
    # servo at its joint point, so a second pass with the point moved to the servo gives the real actuator/horn/back frames; the
    # zero-pose overlap pre-check is taken from that pass.
    import copy
    lay2 = copy.deepcopy(layout)
    drives = {}
    for limb in lay2["limbs"].values():
        for jd in limb["joints"]:
            if jd.get("drive"):
                pname = f"_servo_{jd['name']}"
                lay2.setdefault("points", {})[pname] = jd["drive"]["servo_point"]
                drives[jd["name"]] = dict(jd["drive"])
                jd["point"] = pname
    if drives:
        d2 = interfaces.generate(spec, lay2)
        for jn, dr in drives.items():
            for key in ("actuator", "horn", "back", "keepout", "idler"):
                d["joints"][jn][key] = d2["joints"][jn][key]
            d["joints"][jn]["drive"] = dr
        d["problems"] = d2["problems"]
    d["region"] = "B (upper body: the torso bolted to the pelvis deck and everything it carries)"
    # contract v5: no waist joint. torso_link is a FIXED child of the pelvis (the generator only knows roots and revolute joints)
    if "torso_link" in d["links"]:
        d["links"]["torso_link"]["parent"] = "pelvis"
        d["fixed_joints"] = {"torso_mount": {"parent_link": "pelvis", "child_link": "torso_link", "type": "fixed",
                                             "origin_mm": d["links"]["torso_link"]["origin_mm"],
                                             "note": "bolted torso-pelvis mount, contract_ab.yaml v5 (no waist yaw; DOF 22)"}}
    d["contract_ab"] = yaml.safe_load((HERE / "contract_ab.yaml").read_text(encoding="utf-8"))
    out = HERE / "interfaces_upper.yaml"
    hdr = ("# GENERATED by variants/adam/cad/interfaces/generate.py from layout_v2a_upper.yaml + contract_ab.yaml. Do not edit; re-run.\n")
    out.write_text(hdr + yaml.safe_dump(d, sort_keys=False, default_flow_style=None, width=140), encoding="utf-8")
    print(out, "joints:", len(d["joints"]), "problems:", d["problems"] or "none")
    return 1 if d["problems"] else 0


if __name__ == "__main__":
    sys.exit(main())
