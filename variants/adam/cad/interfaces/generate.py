"""Generate Adam's region-B (upper body) interfaces: variants/adam/cad/interfaces/interfaces_upper.yaml.

    .venv/Scripts/python variants/adam/cad/interfaces/generate.py

Uses the CAD foundation generator (openhumanoid.cad.interfaces.generate) on layout_v2a_upper.yaml, then appends the A<->B contract
(contract_ab.yaml, hand-written: what region A's pelvis must provide). The generator's own `write()` targets generated/ (the
full-body file, written once region A lands); this region keeps its file next to the layout so both regions can be merged later.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT))

from openhumanoid.cad import interfaces  # noqa: E402
from openhumanoid.spec import load_spec  # noqa: E402


def main() -> int:
    spec = load_spec("adam")
    layout = interfaces.load_layout(spec, HERE / "layout_v2a_upper.yaml")
    d = interfaces.generate(spec, layout)
    d["region"] = "B (upper body: waist yaw and everything it carries)"
    d["contract_ab"] = yaml.safe_load((HERE / "contract_ab.yaml").read_text(encoding="utf-8"))
    out = HERE / "interfaces_upper.yaml"
    hdr = ("# GENERATED by variants/adam/cad/interfaces/generate.py from layout_v2a_upper.yaml + contract_ab.yaml. Do not edit; re-run.\n")
    out.write_text(hdr + yaml.safe_dump(d, sort_keys=False, default_flow_style=None, width=140), encoding="utf-8")
    print(out, "joints:", len(d["joints"]), "problems:", d["problems"] or "none")
    return 1 if d["problems"] else 0


if __name__ == "__main__":
    sys.exit(main())
